// Copy the public testnet deployment into the web app.
//
//   npm run sync-deployment
//
// Reads ../docs/testnet-deployment.json (written by scripts/testnet.py deploy)
// and writes lib/deployment.json: contract, deploy ledger, test USDC and every
// demo account. Run it after any contract redeploy, then rebuild and deploy the
// app. Only public data is read or written. Fails loudly on anything missing,
// rather than leaving the app pointing at half an old deployment.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../docs/testnet-deployment.json");
const target = resolve(here, "../lib/deployment.json");

const d = JSON.parse(readFileSync(source, "utf8"));

const contractId = (v, what) => {
  if (typeof v !== "string" || !/^C[A-Z2-7]{55}$/.test(v)) throw new Error(`${what} is missing or isn't a contract address: ${v}`);
  return v;
};
const account = (v, what) => {
  if (typeof v !== "string" || !/^G[A-Z2-7]{55}$/.test(v)) throw new Error(`${what} is missing or isn't an account address: ${v}`);
  return v;
};

if (d.network !== "testnet") throw new Error(`Expected a testnet deployment, got "${d.network}".`);
if (!Number.isInteger(d.deploy_ledger) || d.deploy_ledger <= 0) throw new Error(`deploy_ledger is missing: ${d.deploy_ledger}`);
const [usdcCode, usdcIssuer] = String(d.usdc_asset ?? "").split(":");
if (!usdcCode || usdcIssuer !== d.usdc_issuer) throw new Error(`usdc_asset (${d.usdc_asset}) doesn't match usdc_issuer (${d.usdc_issuer}).`);

const roles = ["admin", "issuer", "store", "store2", "weaver", "investor"];
const out = {
  note: "Generated by `npm run sync-deployment` from docs/testnet-deployment.json. Do not edit by hand.",
  contract: contractId(d.contract, "contract"),
  deployLedger: d.deploy_ledger,
  usdc: contractId(d.usdc, "usdc"),
  usdcCode,
  usdcIssuer: account(d.usdc_issuer, "usdc_issuer"),
  accounts: Object.fromEntries(roles.map((r) => [r, account(d.accounts?.[r], `accounts.${r}`)])),
};

writeFileSync(target, JSON.stringify(out, null, 2) + "\n");
console.log(`lib/deployment.json now points at contract ${out.contract} (deploy ledger ${out.deployLedger}).`);
